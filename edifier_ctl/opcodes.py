# Opcodes that only read state (safe to query with an empty payload).
QUERY_OPCODES = frozenset(o for o, n in OPCODE_NAMES.items() if n.endswith('_query'))

# Everything else changes state or is special (pairing, OTA, logs, reset).
NON_QUERY_OPCODES = frozenset(OPCODE_NAMES) - QUERY_OPCODES

# Query opcodes that drop the BLE link on this speaker when sent (recoverable).
LINK_DROPPERS = frozenset({0xD0, 0xD1, 0xCB})  # battery_query, time_off_set, (unnamed 0xCB)
